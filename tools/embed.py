"""Generate build/embedded.c: the files the program carries and writes into the data folder when it extracts
the disc (open question packs + their index, the HD / widescreen art kit). Only repository files, no Encarta
content.

  python3 tools/embed.py build/embedded.c
"""
import json
import os
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# (path in the data folder, path in the repository)
FILES = [
    ("art/START-HERE.txt", "codex/START-HERE.txt"),
    ("art/PROMPT-HD.txt", "codex/PROMPT.txt"),
    ("art/PROMPT-WIDE.txt", "codex/wide/PROMPT.txt"),
    ("art/HD-ART.md", "docs/HD-ART.md"),
    ("packs/LICENSES.md", "packs/LICENSES.md"),
]


def pack_index():
    rows = []
    for name in sorted(os.listdir(os.path.join(ROOT, "packs"))):
        if not name.endswith(".json") or name == "online_map.json":
            continue
        with open(os.path.join(ROOT, "packs", name), encoding="utf-8") as f:
            d = json.load(f)
        h = d.get("pack", {})
        pid = h.get("id") or os.path.splitext(name)[0]
        rows.append("\t".join([name, pid, h.get("name", pid), h.get("license", ""), str(len(d.get("questions", [])))]))
        FILES.append(("packs/" + name, "packs/" + name))
    FILES.append(("packs/online_map.json", "packs/online_map.json"))
    return ("\n".join(rows) + "\n").encode("utf-8")


def main():
    extra = [("packs/index.txt", pack_index())]
    items = [(dest, open(os.path.join(ROOT, src), "rb").read()) for dest, src in FILES] + extra
    out = ["/* Generated by tools/embed.py - do not edit. */", '#include "mx.h"', ""]
    table = []
    total = 0
    for i, (dest, data) in enumerate(items):
        z = zlib.compress(data, 9)
        use_z = len(z) < len(data)
        blob = z if use_z else data
        total += len(blob)
        out.append("static const unsigned char f%d[%d] = {" % (i, len(blob)))
        for k in range(0, len(blob), 32):
            out.append(",".join(str(b) for b in blob[k:k + 32]) + ",")
        out.append("};")
        table.append('    {"%s", f%d, %d, %d},' % (dest, i, len(blob), int(use_z)))
    out.append("const MXFile mx_embedded[] = {")
    out += table
    out.append("    {0, 0, 0, 0}};")
    os.makedirs(os.path.dirname(os.path.abspath(sys.argv[1])), exist_ok=True)
    with open(sys.argv[1], "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("embedded: %d files, %d bytes" % (len(items), total))


if __name__ == "__main__":
    main()
