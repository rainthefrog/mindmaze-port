"""Generate src/art/mm_art_text.h (picture descriptions, sheet groups, widescreen tasks) from the reference
Python tools, so the game writes the same sheet notes as tools/art/mm_sheets.py and mm_wide_sheets.py.

  python3 tools/art/gen_art_text.py src/art/mm_art_text.h
"""
import os
import sys

out_path = sys.argv[1]
sys.argv = [sys.argv[0], "/nonexistent"]          # the tools read their data folder from argv[1] at import
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mm_sheets  # noqa: E402
import mm_wide_sheets  # noqa: E402


def c(s):
    out = '"'
    for ch in s:
        if ch == "\\":
            out += "\\\\"
        elif ch == '"':
            out += '\\"'
        elif ch == "\n":
            out += "\\n"
        elif ord(ch) < 32 or ord(ch) > 126:
            out += "".join("\\x%02x\"\"" % b for b in ch.encode("utf-8"))
        else:
            out += ch
    return out + '"'


L = ["/* Generated by tools/art/gen_art_text.py from tools/art/mm_sheets.py and mm_wide_sheets.py - do not edit. */",
     "#pragma once", ""]
L.append("static const struct { const char *file, *desc; } ART_DESC[] = {")
for k in sorted(mm_sheets.D):
    L.append("    {%s, %s}," % (c(k), c(mm_sheets.D[k])))
for k in sorted(mm_sheets.UI):
    L.append("    {%s, %s}," % (c("res/%d.bmp" % k), c(mm_sheets.UI[k])))
L.append("    {0, 0}};")
L.append("")
L.append("static const char *const ART_GROUP_FILES[] = {")
groups = []
for prefix, files, note in mm_sheets.GROUPS:
    start = sum(len(g[1]) + 1 for g in groups)
    groups.append((prefix, files, note))
    L.append("    " + ", ".join(c(f) for f in files) + ", 0,")
L.append("};")
L.append("static const struct { const char *prefix, *note; int first; } ART_GROUPS[] = {")
start = 0
for prefix, files, note in groups:
    L.append("    {%s, %s, %d}," % (c(prefix), c(note), start))
    start += len(files) + 1
L.append("    {0, 0, 0}};")
L.append("")
L.append("/* widescreen: picture, x in the room view, kind, TASK text (NULL = the kind's), STRETCH bands (0 = FILL) */")
L.append("static const struct { const char *file; int view_x; const char *kind, *task; int nbands; int bands[4][4]; } WIDE_ITEMS[] = {")
for f, vx, kind in mm_wide_sheets.ITEMS:
    bands = mm_wide_sheets.STRETCH.get(f, [])
    b = ", ".join("{%d, %d, %d, %d}" % tuple(x) for x in bands) if bands else "{0}"
    task = mm_wide_sheets.EXTRA.get(f)
    L.append("    {%s, %d, %s, %s, %d, {%s}}," % (c(f), vx, c(kind), c(task) if task else "0", len(bands), b))
L.append("    {0, 0, 0, 0, 0, {{0}}}};")
L.append("static const struct { const char *kind, *what; } WIDE_WHAT[] = {")
for k, v in mm_wide_sheets.WHAT.items():
    L.append("    {%s, %s}," % (c(k), c(v)))
L.append("    {0, 0}};")
L.append("enum { WIDE_EXT = %d, WIDE_VIEW_W = %d, ROOM_VP_X = %d, ROOM_VP_Y = %d };" % (
    mm_wide_sheets.EXT, mm_wide_sheets.VIEW_W, mm_wide_sheets.ROOM_VP[0], mm_wide_sheets.ROOM_VP[1]))
L.append("static const struct { const char *name, *side; int bx, by, ox, oy; } ROOM_LINES[] = {")
for name, side, (bx, by), (ox, oy) in mm_wide_sheets.ROOM_LINES:
    L.append("    {%s, %s, %d, %d, %d, %d}," % (c(name), c(side), bx, by, ox, oy))
L.append("    {0, 0, 0, 0, 0, 0}};")
L.append("static const char *const ROOM_SHEETS[] = {%s, 0};" % ", ".join(c(f) for f in mm_wide_sheets.ROOM_SHEETS))
with open(out_path, "w", newline="\n") as fh:
    fh.write("\n".join(L) + "\n")
print("art texts: %d descriptions, %d groups, %d widescreen pictures" % (
    len(mm_sheets.D) + len(mm_sheets.UI), len(groups), len(mm_wide_sheets.ITEMS)))
