/* Built-in extractor: builds the game's data folder from the player's own Encarta 2006 disc.
 *
 * Portable C (no platform calls); the platform passes file access as callbacks (MXIO). The same code runs in the
 * Windows exe (first start), the command-line tool (tools/extract/mmextract.c) and the web / Android build.
 * tools/extract/extract.py is the reference implementation in Python; both write the same data folder.
 */
#pragma once
#include <stddef.h>
#include <stdint.h>

typedef struct MXIO MXIO;
struct MXIO {
    /* open a file for reading (UTF-8 path); NULL if missing. *size receives its length */
    void *(*open)(MXIO *io, const char *path, int64_t *size);
    int (*read)(MXIO *io, void *file, int64_t offset, void *buf, size_t n);    /* 1 = all n bytes read */
    void (*close)(MXIO *io, void *file);
    /* write a file below the output folder ("res/29150.bmp" creates res/); 1 = ok */
    int (*write)(MXIO *io, const char *relpath, const void *data, size_t n);
    /* optional: progress 0..100 and a short description of the step */
    void (*progress)(MXIO *io, int percent, const char *step);
    void *user;
};

/* source: a disc image (.iso), or a folder (mounted disc, drive, or a copy of the files; the files are looked
 * up as EE/ENCARTA/<name>, EE/KIDS/<name> and <name>, in upper and lower case). Returns 1 on success, else 0
 * and a message for the player in err. */
int mx_extract(MXIO *io, const char *source, char *err, int errlen);

#define MX_VERSION "1.0"

/* another disc's questions (Encarta 95-98 or 2006, or a folder holding MINDMAZE.DB + .IDX) into an existing data
 * folder: editions/<id>/mindmaze.db + .idx in the 2006 layout, plus its extra music (mx_edition.c). id[>=16],
 * name[>=64] and *count receive the edition. 1 = done, 0 = error with a message for the player in err */
int mx_add_edition(MXIO *io, const char *source, char *id, int idlen, char *name, int namelen, int *count, char *err, int errlen);

/* files built into the program (open question packs, the art kit), written into the data folder after the disc's
 * contents. The list ends with name NULL; zlib = 1: data is a zlib stream. Generated by tools/embed.py
 * (build/embedded.c, array mx_embedded); the platform sets mx_files = mx_embedded before extracting. */
typedef struct { const char *name; const unsigned char *data; size_t size; int zlib; } MXFile;
extern const MXFile *mx_files;
extern const MXFile mx_embedded[];

/* ---- parts, exposed for the tests ---- */
int mx_lzx_decompress(const uint8_t *in, size_t inlen, uint8_t *out, size_t outlen, int window_bits,
                      int reset_frames, char *err, int errlen);
/* MINDMAZE.EIT (ITOL/ITLS archive) in memory: calls fn for every file in it; 0 + err on a format problem */
int mx_itol_files(const uint8_t *d, size_t n, void (*fn)(void *ctx, const char *name, const uint8_t *data, size_t len),
                  void *ctx, char *err, int errlen);
void mx_sha256(const void *data, size_t n, uint8_t out[32]);
/* zlib stream -> malloc'd bytes (*outlen); NULL on error */
uint8_t *mx_inflate_zlib(const uint8_t *in, size_t inlen, size_t *outlen);
/* raw deflate stream (no header) -> malloc'd bytes, at most maxout; *used = input bytes of the stream */
uint8_t *mx_inflate_raw(const uint8_t *in, size_t inlen, size_t maxout, size_t *outlen, size_t *used);
uint32_t mx_crc32(const void *data, size_t n);
/* older editions (mx_old.c): baggage file systems (calls fn per file; returns the file count, < 0 = not a baggage
 * file), KWAJ-compressed *.DI$ -> .bmp, Encarta 95 picture|mask -> cyan key (NULL: not a masked picture) */
int mx_old_files(const uint8_t *d, size_t n, void (*fn)(void *ctx, const char *name, const uint8_t *data, size_t len), void *ctx);
uint8_t *mx_kwaj(const uint8_t *in, size_t n, size_t *outlen);
uint8_t *mx_unmask95(const uint8_t *bmp, size_t n, size_t *outlen);
/* RIFF WAVE in MS ADPCM (or 16-bit PCM) -> malloc'd 16-bit PCM WAVE; NULL on error */
uint8_t *mx_wav_to_pcm(const uint8_t *wav, size_t n, size_t *outlen);
/* classic HFS disc image (Macintosh; Apple partition map or bare volume), already open as f (size bytes): a file's
 * data fork (rsrc 0) or resource fork (rsrc 1) as malloc'd bytes, or NULL. dir = folder path from the volume root,
 * '/'-separated ("" = root), e.g. dir "Installer Files", file "Encarta 96" (mx_edition.c, 2026-11-18) */
uint8_t *mx_hfs_file(MXIO *io, void *f, int64_t size, const char *dir, const char *file, int rsrc, size_t *len);
